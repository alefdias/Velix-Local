  Future<void> init() async {
    try {
      final stored = await DatabaseService.instance.getSetting('app_language');
      _currentLanguage = stored ?? 'auto';
      _updateEffectiveLanguage();
      notifyListeners();
    } catch (_) {
      _updateEffectiveLanguage();
    }
  }

  void _updateEffectiveLanguage() {
    if (_currentLanguage == 'auto') {
      final systemLocale = PlatformDispatcher.instance.locale.languageCode.toLowerCase();
      if (_translations.containsKey(systemLocale)) {
        _effectiveLanguage = systemLocale;
      } else {
        _effectiveLanguage = 'en'; // fallback global
      }
    } else {
      _effectiveLanguage = _translations.containsKey(_currentLanguage) ? _currentLanguage : 'en';
    }
  }

  Future<void> setLanguage(String langCode) async {
    _currentLanguage = langCode;
    _updateEffectiveLanguage();
    await DatabaseService.instance.setSetting('app_language', langCode);
    notifyListeners();
  }

  String translate(String key) {
    final langMap = _translations[_effectiveLanguage] ?? _translations['en'] ?? _translations['pt']!;
    if (langMap.containsKey(key)) {
      return langMap[key]!;
    }
    // Fallback inglês
    final enMap = _translations['en'];
    if (enMap != null && enMap.containsKey(key)) {
      return enMap[key]!;
    }
    // Fallback português
    final ptMap = _translations['pt'];
    if (ptMap != null && ptMap.containsKey(key)) {
      return ptMap[key]!;
    }
    return key;
  }

